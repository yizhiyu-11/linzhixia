/** 单个 face id → {name, emotion} */
export function faceInfo(id) {
  const n = Number(id);
  const hit = FACES[n];
  return hit ? { name: hit[0], emotion: hit[1] } : { name: '表情', emotion: '平静' };
}

/**
 * 把一串 face id 变成文本提示：`[表情:白眼]`
 * 这样感知层和生成层都能看到，成本为零。
 */
export function facesToText(ids = []) {
  if (!ids?.length) return '';
  return ids.map((id) => `[表情:${faceInfo(id).name}]`).join('');
}

/** 给感知层用：这些表情的整体情绪 */
export function faceEmotion(ids = []) {
  const counts = new Map();
  for (const id of ids || []) {
    const e = faceInfo(id).emotion;
    counts.set(e, (counts.get(e) || 0) + 1);
  }
  let best = '平静';
  let n = 0;
  for (const [e, c] of counts) {
    if (c > n) {
      n = c;
      best = e;
    }
  }
  return best;
}
